# ------------------------------------------------------------------ setup --
def repo_dir(a):
    for d in (a.repo, os.environ.get("MOS_FLEET_REPO")):
        if d:
            return os.path.abspath(os.path.expanduser(d))
    top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if top.returncode == 0 and os.path.isfile(os.path.join(top.stdout.strip(), "fleet.toml")):
        return top.stdout.strip()
    return os.path.expanduser(CFG["repo"])


def load(a, check=True):
    d = repo_dir(a)
    if not os.path.isfile(os.path.join(d, "fleet.toml")):
        raise Fail(f"No fleet repository in {d} (mos-fleet clone SERVER, or --repo DIR).")
    r = Repo(d)
    if check and r.errors:
        raise Fail("The repository has problems:\n  " + "\n  ".join(r.errors))
    return r


def ssh_opts(known=KNOWN, alias=SERVER_ALIAS):
    return ["-o", f"UserKnownHostsFile={known}", "-o", "GlobalKnownHostsFile=/dev/null",
            "-o", "StrictHostKeyChecking=yes", "-o", f"HostKeyAlias={alias}"]


def pin(server_key):
    os.makedirs(CONF, mode=0o700, exist_ok=True)
    write_atomic(KNOWN, f"{SERVER_ALIAS} {server_key}\n", mode=0o644)


def server_argv(server, *remote):
    host, port = split_server(server)
    return ["ssh", *ssh_opts(), "-p", port, f"fleet@{host}", shlex.join(remote)]


def remote(r, *args, input=None, capture=True, check=True):
    """A command on the server, as fleet@SERVER."""
    pin(r.fleet["server_host_key"])
    p = subprocess.run(server_argv(r.fleet["server"], *args), input=input, text=True,
                       capture_output=capture)
    if check and p.returncode != 0:
        raise Fail((p.stderr or "").strip().removeprefix("mos-fleet: ") if capture else f"the server said no ({p.returncode})")
    return p.stdout if capture else p.returncode


def git_ssh_command():
    return "ssh " + " ".join(shlex.quote(x) for x in ssh_opts())


def git(d, *args, check=True, capture=True):
    return run(["git", "-C", d, *args], check=check, capture=capture)


def ensure_identity(d, name, email):
    """Commits need an author: this repository's own, if git has none."""
    if not subprocess.run(["git", "-C", d, "config", "user.name"], capture_output=True).stdout.strip():
        git(d, "config", "user.name", name)
    if not subprocess.run(["git", "-C", d, "config", "user.email"], capture_output=True).stdout.strip():
        git(d, "config", "user.email", email)


def keyscan(server, expected=None):
    """The server's SSH key, confirmed against the fingerprint the server's
    console printed (`mos-fleet server init`)."""
    host, port = split_server(server)
    out = run(["ssh-keyscan", "-T", "15", "-t", "ed25519", "-p", port, host], check=False)
    lines = [line for line in out.splitlines() if line and not line.startswith("#")]
    if not lines:
        raise Fail(f"No answer from {server} (ssh-keyscan): is it on, and its name right?")
    key = ssh_key(lines[0].split(None, 1)[1])
    fp = fingerprint(key)
    if expected:
        if expected != fp:
            raise Fail(f"{server}'s key is {fp}, not {expected}: stop, and check (wrong address, or someone in between).")
    else:
        say(f"{server}'s SSH key: {fp}")
        if input("Is this the fingerprint `mos-fleet server init` printed on the server's screen? [y/N] ").strip().lower() != "y":
            raise Fail("Not confirmed: nothing done.")
    return key


def age_recipient():
    """Your admin key (age): recovery keys are encrypted for its public half."""
    if not os.path.exists(ADMIN_KEY):
        os.makedirs(CONF, mode=0o700, exist_ok=True)
        run(["age-keygen", "-o", ADMIN_KEY])
        os.chmod(ADMIN_KEY, 0o600)
        say(f"Your admin key: {ADMIN_KEY}. Back it up now, offline (print it): without it you can't read recovery keys.")
    out = run(["age-keygen", "-y", ADMIN_KEY]).strip()
    if not AGE_RE.fullmatch(out):
        raise Fail(f"{ADMIN_KEY}: not an age key")
    return out


def read_key_arg(x):
    """An SSH public key: a file, or the line itself."""
    p = os.path.expanduser(x)
    if os.path.isfile(p):
        x = open(p).read().strip()
    return ssh_key(x)


# ----------------------------------------------------------- transactions --
class Change:
    """Edit files of the repository; check the result; commit, or put
    everything back if it isn't valid."""

    def __init__(self, r, message):
        self.r, self.d, self.message = r, r.root, message
        self.saved = {}

    def write(self, rel, text):
        p = os.path.join(self.d, rel)
        if rel not in self.saved:
            self.saved[rel] = open(p).read() if os.path.exists(p) else None
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as fh:
            fh.write(text)

    def remove(self, rel):
        p = os.path.join(self.d, rel)
        if rel not in self.saved:
            self.saved[rel] = open(p).read() if os.path.exists(p) else None
        if os.path.exists(p):
            os.remove(p)
            try:
                os.removedirs(os.path.dirname(p))  # an emptied hosts/NAME
            except OSError:
                pass

    def commit(self, push=False):
        r = Repo(self.d)
        if r.errors:
            for rel, text in self.saved.items():
                p = os.path.join(self.d, rel)
                if text is None:
                    if os.path.exists(p):
                        os.remove(p)
                else:
                    with open(p, "w") as fh:
                        fh.write(text)
            raise Fail("Not changed, it wouldn't be valid:\n  " + "\n  ".join(r.errors))
        git(self.d, "add", "-A", "--", *self.saved)
        if subprocess.run(["git", "-C", self.d, "diff", "--cached", "--quiet"]).returncode == 0:
            say("Nothing changed.")
            return r
        git(self.d, "commit", "-q", "-m", self.message)
        say(f"Committed: {self.message}")
        if push:
            do_push(self.d)
        else:
            say("   (mos-fleet push sends it to the server)")
        return r


def do_push(d, branch="main", force=False):
    p = subprocess.run(["git", "-C", d, "push", "-q"] + (["-f"] if force else []) + ["origin", branch],
                       capture_output=True, text=True)
    out = "\n".join(line.removeprefix("remote: ") for line in (p.stderr + p.stdout).splitlines() if line.strip())
    if p.returncode != 0:
        raise Fail(f"git push refused:\n{out}")
    if out:
        say(out)
    say(f"Pushed {branch}.")


def person_file(r, name):
    if not PERSON_RE.fullmatch(name):
        raise Fail(f"{name!r}: a user name (lowercase letters, digits, - and _)")
    return f"people/{name}.toml"


def write_person(c, name, p):
    order = ["name", "email", "uid", "groups", "ssh_keys", "age_recipient", "disabled"]
    out = {k: p[k] for k in order if k in p and p[k] is not None and not (k == "disabled" and not p[k])}
    c.write(f"people/{name}.toml", toml_dump(out))


def write_groups(c, groups):
    c.write("groups.toml", groups_text(groups))


def groups_text(groups):
    lines = ["# Groups: who may log in on which profiles' computers, and with sudo.",
             f"# {ADMINS} may log in everywhere, with sudo, and reach the server."]
    for g, t in groups.items():
        lines.append("")
        lines.append(toml_dump({"gid": t["gid"], "profiles": t.get("profiles", []), "sudo": t.get("sudo", False),
                                "description": t.get("description")}, f"[{g}]").rstrip("\n"))
    return "\n".join(lines) + "\n"


def fresh_person(r, name):
    p = read_toml(os.path.join(r.root, "people", f"{name}.toml")) if name in r.people else None
    if p is None:
        raise Fail(f"No person {name} (people/{name}.toml).")
    return p


def next_id(used, start):
    return max([start - 1, *used]) + 1


