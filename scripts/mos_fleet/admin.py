def cmd_init(a):
    d = os.path.abspath(os.path.expanduser(a.dir or CFG["repo"]))
    if os.path.exists(os.path.join(d, "fleet.toml")):
        raise Fail(f"{d} already holds a fleet repository.")
    if not PERSON_RE.fullmatch(a.admin):
        raise Fail("--admin: your user name (lowercase letters, digits, - and _)")
    key = keyscan(a.server, a.fingerprint)
    pin(key)
    info = json.loads(run(server_argv(a.server, "info")))
    if info.get("main"):
        raise Fail("The server already has a fleet repository: mos-fleet clone instead.")
    ssh = read_key_arg(a.ssh_key or "~/.ssh/id_ed25519.pub")
    recipient = age_recipient()
    os.makedirs(d, exist_ok=True)
    host, port = split_server(a.server)
    fleet = {"organization": a.organization, "server": a.server, "server_host_key": key}
    if info.get("tang_thumbprint"):
        fleet["tang"] = {"url": f"http://{host}:{info.get('tang_port', 7654)}", "thumbprint": info["tang_thumbprint"]}
    nf = CFG["new_fleet"]
    fleet["checkin"] = {"interval": nf["checkin_interval"]}
    fleet["logs"] = {"min_priority": nf["log_min_priority"], "units": nf["log_units"], "keep_days": nf["log_keep_days"]}
    files = {
        "fleet.toml": toml_dump(fleet, "# The organization and its fleet server. Written by mos-fleet init."),
        f"people/{a.admin}.toml": toml_dump({"name": a.full_name, "uid": a.uid, "groups": [ADMINS],
                                             "ssh_keys": [ssh], "age_recipient": recipient}),
        "common.nix": COMMON_NIX,
        "flake.nix": (open(a.flake).read() if a.flake else FLAKE_NIX).replace("@MECCANICOS@", a.meccanicos),
        "README.md": README_MD.replace("@ORG@", a.organization),
        "hosts/.keep": "",
        "profiles/.keep": "",
        "groups.toml": groups_text({ADMINS: {"gid": CFG["admins_gid"], "profiles": ["*"], "sudo": True,
                                             "description": "fleet admins: everywhere, with sudo; the server"}}),
    }
    for rel, text in files.items():
        os.makedirs(os.path.dirname(os.path.join(d, rel)) or d, exist_ok=True)
        with open(os.path.join(d, rel), "w") as fh:
            fh.write(text)
    r = Repo(d)
    if r.errors:
        raise Fail("The new repository isn't valid:\n  " + "\n  ".join(r.errors))
    git(d, "init", "-q", "-b", "main")
    ensure_identity(d, a.full_name, f"{a.admin}@{host}")
    if not a.no_lock:
        say("Pinning the MeccanicOS version (nix flake lock)…")
        git(d, "add", "-A")
        run(["nix", "flake", "lock"], cwd=d, capture=False)
    git(d, "add", "-A")
    git(d, "commit", "-q", "-m", f"{a.organization}'s fleet")
    git(d, "remote", "add", "origin", f"ssh://fleet@{host}:{port}/fleet.git")
    git(d, "config", "core.sshCommand", git_ssh_command())
    do_push(d)
    say(f"\nThe fleet repository: {d}\nNext: mos-fleet profile add office   (a kind of computer)")


def cmd_clone(a):
    d = os.path.abspath(os.path.expanduser(a.dir or CFG["repo"]))
    key = keyscan(a.server, a.fingerprint)
    pin(key)
    host, port = split_server(a.server)
    run(["git", "-c", f"core.sshCommand={git_ssh_command()}", "clone", "-q", f"ssh://fleet@{host}:{port}/fleet.git", d])
    git(d, "config", "core.sshCommand", git_ssh_command())
    me = getpass.getuser()
    ensure_identity(d, me, f"{me}@{host}")
    r = Repo(d)
    if r.fleet.get("server_host_key") != key:
        warn("Note: fleet.toml's server_host_key differs from the key you confirmed.")
    say(f"The fleet repository: {d}")
    say(f"Your admin key's public half, for people/YOU.toml (age_recipient): {age_recipient()}")


def cmd_admin_key(a):
    say(age_recipient())


def cmd_validate(a):
    r = load(a, check=False)
    if r.errors:
        raise Fail("Not valid:\n  " + "\n  ".join(r.errors))
    say(f"Files: ok ({len(r.hosts)} computers, {len(r.people)} people, {len(r.groups)} groups, {len(r.profiles)} profiles).")
    if a.no_eval:
        return
    if git(r.root, "status", "--porcelain").strip():
        say("   (uncommitted changes: Nix sees the committed files and the tracked ones)")
    say("Evaluating every computer's system with Nix…")
    out = run(["nix", "eval", "--json", "--no-write-lock-file", f"{r.root}#nixosConfigurations", "--apply",
               "cs: builtins.mapAttrs (_: c: c.config.system.build.toplevel.drvPath) cs"], cwd=r.root)
    say(f"Nix: ok ({len(json.loads(out))} computers evaluate).")


def cmd_push(a):
    r = load(a)
    if not a.no_eval:
        cmd_validate(a)
    do_push(r.root, a.branch, force=a.branch != "main" and a.force)


def cmd_person(a):
    r = load(a)
    if a.action == "list":
        for n, p in sorted(r.people.items()):
            say(f"{n:16} {p['uid']:6} {p['name'][:30]:30} {','.join(p.get('groups', [])):30}"
                f"{' DISABLED' if p.get('disabled') else ''}{' (admin key)' if p.get('age_recipient') else ''}")
        return
    rel = person_file(r, a.name)
    c = Change(r, f"person {a.action} {a.name}")
    if a.action == "add":
        if a.name in r.people:
            raise Fail(f"{a.name} is already there: mos-fleet person edit {a.name} …")
        p = {"name": a.full_name, "email": a.email, "uid": a.uid or next_id([x["uid"] for x in r.people.values()], CFG["first_uid"]),
             "groups": a.group or [], "ssh_keys": [read_key_arg(k) for k in a.ssh_key or []],
             "age_recipient": a.age_recipient}
        write_person(c, a.name, p)
    elif a.action == "edit":
        p = fresh_person(r, a.name)
        if a.full_name:
            p["name"] = a.full_name
        if a.email is not None:
            p["email"] = a.email or None
        for g in a.add_group or []:
            p["groups"] = sorted(set(p.get("groups", [])) | {g})
        for g in a.remove_group or []:
            p["groups"] = [x for x in p.get("groups", []) if x != g]
        for k in a.add_ssh_key or []:
            p["ssh_keys"] = p.get("ssh_keys", []) + [read_key_arg(k)]
        for k in a.remove_ssh_key or []:
            keep = [x for x in p.get("ssh_keys", []) if fingerprint(ssh_key(x)) != k]
            if len(keep) == len(p.get("ssh_keys", [])):
                raise Fail(f"No key with fingerprint {k} (mos-fleet person show {a.name}).")
            p["ssh_keys"] = keep
        if a.age_recipient is not None:
            p["age_recipient"] = a.age_recipient or None
        write_person(c, a.name, p)
    elif a.action in ("disable", "enable"):
        p = fresh_person(r, a.name)
        p["disabled"] = a.action == "disable"
        write_person(c, a.name, p)
    elif a.action == "remove":
        fresh_person(r, a.name)
        c.remove(rel)
    elif a.action == "show":
        p = fresh_person(r, a.name)
        say(open(os.path.join(r.root, rel)).read().rstrip())
        for k in p.get("ssh_keys", []):
            say(f"# {fingerprint(ssh_key(k))}")
        where = [h for h in sorted(r.hosts) if a.name in r.allowed(h)]
        say(f"# may log in on: {', '.join(where) or '(no computer yet)'}")
        return
    c.commit(a.push)


def cmd_group(a):
    r = load(a)
    groups = {g: dict(t) for g, t in r.groups.items()}
    if a.action == "list":
        for g, t in groups.items():
            members = sorted(n for n, p in r.people.items() if g in p.get("groups", []))
            say(f"{g:16} {t['gid']:6} {'sudo ' if t.get('sudo') else '     '}profiles {','.join(t.get('profiles', [])):20}"
                f" {len(members)} member(s): {', '.join(members)}")
        return
    c = Change(r, f"group {a.action} {a.name}")
    if a.action == "add":
        if a.name in groups:
            raise Fail(f"Group {a.name} exists.")
        groups[a.name] = {"gid": a.gid or next_id([t["gid"] for t in groups.values()], CFG["first_gid"]),
                          "profiles": a.profile or [], "sudo": bool(a.sudo), "description": a.description}
    elif a.action == "edit":
        if a.name not in groups:
            raise Fail(f"No group {a.name}.")
        t = groups[a.name]
        t["profiles"] = sorted((set(t.get("profiles", [])) | set(a.add_profile or [])) - set(a.remove_profile or []))
        if a.sudo is not None:
            t["sudo"] = a.sudo
        if a.description is not None:
            t["description"] = a.description or None
    elif a.action == "remove":
        if a.name == ADMINS:
            raise Fail(f"{ADMINS} stays.")
        members = [n for n, p in r.people.items() if a.name in p.get("groups", [])]
        if members:
            raise Fail(f"{a.name} still has members: {', '.join(members)} (mos-fleet member remove …).")
        groups.pop(a.name, None)
    write_groups(c, groups)
    c.commit(a.push)


def cmd_member(a):
    r = load(a)
    p = fresh_person(r, a.name)
    if a.group not in r.groups:
        raise Fail(f"No group {a.group}.")
    gs = set(p.get("groups", []))
    gs = gs | {a.group} if a.action == "add" else gs - {a.group}
    p["groups"] = sorted(gs)
    c = Change(r, f"member {a.action} {a.group} {a.name}")
    write_person(c, a.name, p)
    c.commit(a.push)


def cmd_profile(a):
    r = load(a)
    if a.action == "list":
        for p in sorted(r.profiles):
            gs = [g for g in r.groups if r.allows(g, p) and g != ADMINS]
            say(f"{p:16} computers: {', '.join(r.hosts_of(p)) or '-':30} groups: {', '.join(gs) or '-'}")
        return
    if not PROFILE_RE.fullmatch(a.name):
        raise Fail("A profile name: lowercase letters, digits and -.")
    c = Change(r, f"profile {a.action} {a.name}")
    groups = {g: dict(t) for g, t in r.groups.items()}
    if a.action == "add":
        if a.name in r.profiles:
            raise Fail(f"Profile {a.name} exists: edit profiles/{a.name}.nix")
        c.write(f"profiles/{a.name}.nix", PROFILE_NIX.replace("@NAME@", a.name))
        if not a.no_group and a.name not in groups and PERSON_RE.fullmatch(a.name):
            groups[a.name] = {"gid": next_id([t["gid"] for t in groups.values()], CFG["first_gid"]), "profiles": [a.name],
                              "sudo": False, "description": f"people who use the {a.name} computers"}
            write_groups(c, groups)
            say(f"Also the group {a.name}, whose members may log in on its computers (mos-fleet member add {a.name} NAME).")
    elif a.action == "remove":
        if r.hosts_of(a.name):
            raise Fail(f"Computers still use it: {', '.join(r.hosts_of(a.name))}.")
        c.remove(f"profiles/{a.name}.nix")
        for g, t in list(groups.items()):
            t["profiles"] = [p for p in t.get("profiles", []) if p != a.name]
        write_groups(c, groups)
    c.commit(a.push)


def stick_dir(to):
    if to:
        base = os.path.abspath(os.path.expanduser(to))
    else:
        subprocess.run(["usb-vault", "stick"], capture_output=True, timeout=120)
        if not os.path.isdir(CFG["stick"]):
            raise Fail("No MeccanicOS stick found: plug it in (or --to DIR).")
        base = CFG["stick"]
    return os.path.join(base, "meccanicos", "fleet")


def cmd_host(a):
    r = load(a)
    if a.action == "list":
        for h, t in sorted(r.hosts.items()):
            say(f"{h:16} {t['profile']:12} {t.get('branch', 'main'):10} {t['unlock']:8} {fingerprint(t['_key'])}")
        return
    if a.action == "pending":
        say(remote(r, "enroll-list").rstrip() or "Nothing pending.")
        return
    if not HOST_RE.fullmatch(a.name):
        raise Fail("A computer name: lowercase letters, digits and -.")
    if a.action == "prepare":
        return host_prepare(a, r)
    if a.action == "add":
        return host_add(a, r)
    if a.name not in r.hosts:
        raise Fail(f"No computer {a.name}.")
    t = read_toml(os.path.join(r.root, "hosts", a.name, "host.toml"))
    c = Change(r, f"host {a.action} {a.name}")
    if a.action == "set":
        for k in ("profile", "branch", "unlock"):
            if getattr(a, k):
                t[k] = getattr(a, k)
        c.write(f"hosts/{a.name}/host.toml", toml_dump(t))
    elif a.action == "retire":
        for f in glob.glob(os.path.join(r.root, "hosts", a.name, "*")):
            c.remove(os.path.relpath(f, r.root))
        say("Its recovery key stays on the server (mos-fleet recover still works).")
    c.commit(a.push)


def host_prepare(a, r):
    if a.profile not in r.profiles:
        raise Fail(f"No profile {a.profile}: mos-fleet profile add {a.profile} (and push).")
    if a.unlock not in UNLOCK:
        raise Fail(f"--unlock: one of {', '.join(UNLOCK)}")
    if a.unlock == "tang" and not r.fleet.get("tang"):
        raise Fail("fleet.toml has no [tang]: the server's Tang isn't known.")
    if a.name in r.hosts and not a.force:
        raise Fail(f"{a.name} is already in the fleet. Reinstalling it: --force.")
    recipients = r.recipients()
    out = os.path.join(stick_dir(a.to), a.name)
    with tempfile.TemporaryDirectory() as tmp:
        run(["ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", f"enroll-{a.name}", "-f", f"{tmp}/key"])
        pub = ssh_key(open(f"{tmp}/key.pub").read())
        args = ["enroll-create", a.name, "--profile", a.profile, "--unlock", a.unlock, "--branch", a.branch, "--key", pub,
                "--days", str(CFG["enroll_days"])]
        if a.disk_serial:
            args += ["--disk-serial", a.disk_serial]
        info = json.loads(remote(r, *args))
        if info["server_host_key"] != r.fleet["server_host_key"]:
            raise Fail("The server's key differs from fleet.toml's: stop and check.")
        shutil.rmtree(out, ignore_errors=True)
        os.makedirs(out)
        conf = {"version": 2, "organization": r.fleet["organization"], "hostname": a.name, "profile": a.profile,
                "server": r.fleet["server"], "server_host_key": r.fleet["server_host_key"],
                "unlock": {"method": a.unlock, **({"tang_url": r.fleet["tang"]["url"],
                                                   "tang_thumbprint": r.fleet["tang"]["thumbprint"]}
                                                  if a.unlock == "tang" else {})},
                "install": {"disk_serial": a.disk_serial} if a.disk_serial else None}
        head = f"# Written by mos-fleet host prepare on {datetime.date.today()}. For mos-install (organization install)."
        write_atomic(os.path.join(out, "corporate.config"), toml_dump(conf, head), 0o600)
        shutil.copyfile(f"{tmp}/key", os.path.join(out, "enroll.key"))
        os.chmod(os.path.join(out, "enroll.key"), 0o600)
        write_atomic(os.path.join(out, "admins.txt"), "\n".join(recipients) + "\n", 0o644)
    subprocess.run(["sync"])
    say(f"Ready: {out}")
    say(f"   {a.name}: profile {a.profile}, unlock {a.unlock}; a one-time key, valid {CFG['enroll_days']} days.")
    say("Boot the computer from this stick and choose Install: it offers the organization install.")
    say(f"After its first start it introduces itself to the server; then: mos-fleet host add {a.name}")


def host_add(a, r):
    e = json.loads(remote(r, "enroll-show", a.name))
    if not e.get("used_on"):
        raise Fail(f"{a.name} hasn't introduced itself yet (its first start after the install, on the network).")
    if a.name in r.hosts and not a.force:
        raise Fail(f"{a.name} is already in the fleet. A reinstalled computer: --force.")
    key = ssh_key(e["host_key"])
    facts = e.get("facts") or {}
    say(f"{a.name} introduced itself on {e['used_on']} UTC from {e.get('address')}:")
    say(f"   host key   {fingerprint(key)}")
    say(f"   hostname   {facts.get('hostname', '?')}, {facts.get('os', '')}")
    for dk in facts.get("disks", {}).get("blockdevices", []) if isinstance(facts.get("disks"), dict) else []:
        say(f"   disk       {dk.get('name')} {dk.get('size')} {dk.get('model') or ''} {dk.get('serial') or ''}")
    say(f"   files      {', '.join(sorted(e.get('files') or {})) or '-'}")
    say("Compare the host key with the one the installer showed on that computer's screen.")
    if not a.yes and input("Add it to the fleet? [y/N] ").strip().lower() != "y":
        raise Fail("Not added.")
    c = Change(r, f"host add {a.name}")
    t = {"profile": e["profile"], "branch": e.get("branch") or "main", "unlock": e["unlock"], "host_key": key,
         "disk_serial": e.get("disk_serial")}
    c.write(f"hosts/{a.name}/host.toml", toml_dump(t, f"# Added by mos-fleet host add on {datetime.date.today()}."))
    for f in HOST_FILES:
        if f in (e.get("files") or {}):
            c.write(f"hosts/{a.name}/{f}", e["files"][f])
        elif os.path.exists(os.path.join(r.root, "hosts", a.name, f)):
            c.remove(f"hosts/{a.name}/{f}")
    c.commit(a.push)
    if not a.push:
        say(f"Review hosts/{a.name}/ (the computer wrote its .nix files), then: mos-fleet push")


def cmd_upgrade(a):
    r = load(a)
    d = r.root
    if git(d, "status", "--porcelain").strip():
        raise Fail("Commit or discard your changes first.")
    git(d, "fetch", "-q", "origin")
    git(d, "checkout", "-q", "main")
    if a.testing:
        git(d, "checkout", "-q", "-B", "testing", "origin/main")
    try:
        run(["nix", "flake", "update", "meccanicos"], cwd=d, capture=False)
        git(d, "add", "flake.lock")
        if subprocess.run(["git", "-C", d, "diff", "--cached", "--quiet"]).returncode == 0:
            say("Already the newest MeccanicOS.")
            return
        git(d, "commit", "-q", "-m", "Newest MeccanicOS")
        a.no_eval = False
        cmd_validate(a)
        do_push(d, "testing" if a.testing else "main", force=a.testing)
        say("Computers whose host.toml says branch = \"testing\" take it; when they're fine: mos-fleet upgrade"
            if a.testing else "Every computer takes it within minutes (a new kernel: at the next restart).")
    finally:
        if a.testing:
            git(d, "checkout", "-q", "main")


def trees(r, base, target):
    """Two commits' repositories (base None: an empty one)."""
    out = []
    for rev in (base, target):
        tmp = tempfile.mkdtemp(prefix="mos-fleet-diff-")
        data = subprocess.run(["git", "-C", r.root, "archive", "--format=tar", rev], capture_output=True)
        if data.returncode != 0:
            raise Fail(f"git archive {rev}: {data.stderr.decode().strip()}")
        subprocess.run(["tar", "-x", "-C", tmp], input=data.stdout, check=True)
        out.append(Repo(tmp))
    return out


def cmd_diff(a):
    r = load(a, check=False)
    subprocess.run(["git", "-C", r.root, "fetch", "-q", "origin"], capture_output=True)
    base, _, target = (a.range or "origin/main..HEAD").partition("..")
    target = target or "HEAD"
    old, new = trees(r, base, target)
    files = git(r.root, "diff", "--name-only", base, target).split()
    if not files:
        say("No changes.")
        return
    everyone = any(f in ("common.nix", "flake.nix", "flake.lock", "fleet.toml") for f in files)
    for h in sorted(set(old.hosts) | set(new.hosts)):
        lines = []
        if h not in old.hosts:
            lines.append("new computer")
        elif h not in new.hosts:
            lines.append("retired")
        else:
            o, n = old.hosts[h], new.hosts[h]
            for k in ("profile", "branch", "unlock", "host_key"):
                if o.get(k) != n.get(k):
                    lines.append(f"{k}: {o.get(k)} -> {n.get(k)}" if k != "host_key" else "a new host key")
            po, pn = old.allowed(h), new.allowed(h)
            for p in sorted(set(pn) - set(po)):
                lines.append(f"+ {p} may log in{' (sudo)' if pn[p] else ''}")
            for p in sorted(set(po) - set(pn)):
                lines.append(f"- {p} may no longer log in")
            for p in sorted(set(po) & set(pn)):
                if po[p] != pn[p]:
                    lines.append(f"  {p}: sudo {'on' if pn[p] else 'off'}")
            prof = n.get("profile")
            touched = [f for f in files if f.startswith(f"hosts/{h}/") or f == f"profiles/{prof}.nix"]
            if everyone or touched:
                lines.append("its system changes (" + ", ".join(touched + [f for f in files if f in (
                    "common.nix", "flake.nix", "flake.lock", "fleet.toml")]) + ")")
        if lines:
            say(f"{h}:")
            for x in lines:
                say(f"   {x}")
    for t in (old, new):
        shutil.rmtree(t.root, ignore_errors=True)


def cmd_password(a):
    r = load(a)
    if a.name not in r.people:
        raise Fail(f"No person {a.name}.")
    if a.stdin:
        pw = sys.stdin.readline().rstrip("\n")
    else:
        pw = getpass.getpass(f"New password for {a.name}: ")
        if getpass.getpass("Again: ") != pw:
            raise Fail("The two differ: nothing changed.")
    if not 8 <= len(pw) <= 128:
        raise Fail("8 to 128 characters.")
    h = run(["mkpasswd", "-m", "yescrypt", "--stdin"], input=pw).strip()
    say(remote(r, "password-set", a.name, input=h + "\n").rstrip())


def cmd_recover(a):
    r = load(a)
    res = json.loads(remote(r, "recover", a.host))
    if not os.path.exists(ADMIN_KEY):
        raise Fail(f"No admin key here ({ADMIN_KEY}): restore it from your backup.")
    p = subprocess.run(["age", "-d", "-i", ADMIN_KEY], input=res["ciphertext"], capture_output=True, text=True)
    if p.returncode != 0:
        raise Fail("Your admin key can't open it (encrypted for other admins' keys).")
    if not res.get("confirmed"):
        warn("Note: from an installation not added to the fleet yet (host add): check the computer.")
    say(f"Recovery key for {a.host} (host key {res.get('host_key_fp')}):\n\n    {p.stdout.strip()}\n")
    say("Type it when the computer asks for the disk password at power-on.")


def cmd_shell(a):
    r = load(a)
    if a.host not in r.hosts:
        raise Fail(f"No computer {a.host}.")
    pin(r.fleet["server_host_key"])
    write_atomic(KNOWN_HOSTS, "".join(f"{h} {t['_key']}\n" for h, t in r.hosts.items()), mode=0o644)
    proxy = shlex.join(server_argv(r.fleet["server"], "relay", a.host)).replace("%", "%%")
    user = a.user or getpass.getuser()
    argv = ["ssh", "-o", f"ProxyCommand={proxy}", *ssh_opts(KNOWN_HOSTS, a.host), f"{user}@{a.host}", *a.command]
    os.execvp("ssh", argv)


def passthrough(r, *args):
    rc = remote(r, *args, capture=False, check=False)
    if rc:
        sys.exit(rc)


def cmd_remote(a):
    r = load(a)
    c = a.cmd
    if c == "status":
        passthrough(r, "status", *([a.host] if a.host else []), *(["--all"] if a.all else []))
    elif c == "logs":
        extra = [x for k, v in (("--unit", a.unit), ("--since", a.since), ("--priority", a.priority),
                                ("--limit", a.limit)) if v is not None for x in (k, str(v))]
        passthrough(r, "logs", a.host, *extra, *(["--follow"] if a.follow else []))
    elif c == "builds":
        passthrough(r, "builds", *([a.host] if a.host else []), *(["--log"] if a.log else []))
    elif c == "deployments":
        passthrough(r, "deployments", a.host)
    elif c == "run":
        tgt = [x for h in a.host or [] for x in ("--host", h)] + (["--profile", a.profile] if a.profile else [])
        passthrough(r, "run", *tgt, "--timeout", str(a.timeout), "--wait", str(a.wait), "--", *a.argv)
    elif c in ("reboot", "switch", "facts"):
        passthrough(r, c, *a.hosts)
    elif c == "jobs":
        passthrough(r, "jobs", *([a.host] if a.host else []))
    elif c == "job":
        passthrough(r, "job", str(a.id))
    elif c == "cancel":
        passthrough(r, "cancel", str(a.id))
    elif c == "audit":
        passthrough(r, "audit", "--limit", str(a.limit))
    elif c == "info":
        say(json.dumps(json.loads(remote(r, "info")), indent=2))


